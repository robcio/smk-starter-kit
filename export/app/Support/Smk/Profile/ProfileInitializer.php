<?php

namespace App\Support\Smk\Profile;

use RuntimeException;
use Symfony\Component\Yaml\Yaml;

final class ProfileInitializer
{
    private const STATE = 'smk-init-state';

    private ProfileFilesystem $fs;

    public function __construct(string $root)
    {
        $this->fs = new ProfileFilesystem($root);
    }

    public static function digest(array $plan): string
    {
        return hash('sha256', ProfileFilesystem::json($plan));
    }

    public function plan(string $profile, array $manifests, string $edition = 'core'): array
    {
        sort($manifests);
        $platform = ManifestValidator::platform();
        $validated = (new ManifestValidator($this->fs))->validate($profile, $manifests, $platform, $edition);
        $this->fs->need($validated['profile']['modules'] === [], 'profile.modules: Core-only generation in MVP; fixtures may validate modules separately');
        $this->pending();
        $sources = array_merge([$profile], $manifests);
        foreach ($validated['manifests'] as $manifest) {
            $sources = array_merge($sources, $manifest['owned_paths']);
        }
        $sources = array_unique($sources);
        sort($sources);
        $inputs = [];
        foreach ($sources as $path) {
            $inputs[$path] = $this->fs->inspect($path);
        }
        $blocks = $validated['manifests']['smk.core']['provides']['blocks'];
        ksort($blocks);
        $render = [];
        $sets = [];
        $labels = ['hero' => 'Sekcja otwierająca', 'rich_text' => 'Tekst sformatowany', 'cta' => 'Wezwanie do działania'];
        foreach ($blocks as $handle => $block) {
            $fieldset = Yaml::parse($this->fs->read($block['fieldset']), Yaml::PARSE_EXCEPTION_ON_INVALID_TYPE);
            $this->fs->need(is_array($fieldset) && isset($fieldset['fields']) && is_array($fieldset['fields']), 'block '.$handle.': fieldset fields required');
            $render[$handle] = ['partial' => substr($block['partial'], strlen('resources/views/'), -strlen('.antlers.html')), 'variants' => $block['variants'], 'default' => $block['default']];
            $sets[$handle] = ['display' => $labels[$handle] ?? $handle, 'fields' => [['import' => basename($block['fieldset'], '.yaml')]]];
        }
        $builder = ['title' => 'SMK — Układ strony (generowany)', 'fields' => [['handle' => 'page_builder', 'field' => ['type' => 'replicator', 'max_sets' => 20, 'validate' => ['nullable', 'array', 'max:20'], 'display' => 'Układ strony', 'instructions' => 'Dodaj najwyżej 20 sekcji. Przeciągnij je, aby zmienić kolejność; przełącznik przy nazwie steruje widocznością.', 'sets' => $sets === [] ? [] : ['core' => ['display' => 'Sekcje podstawowe', 'sets' => $sets]]]]]];
        $bytes = [
            ManifestValidator::OUTPUTS[0] => "# Generated by SMK profile initializer; do not edit.\n".Yaml::dump($builder, 12, 2),
            ManifestValidator::OUTPUTS[1] => ProfileFilesystem::json(['generator_version' => 1, 'profile_schema' => 1, 'id' => 'core', 'core_contract_version' => 1, 'core_version' => $validated['manifests']['smk.core']['version'], 'modules' => [], 'render_map_sha256' => hash('sha256', ProfileFilesystem::json((object) $render))]),
            ManifestValidator::OUTPUTS[2] => ProfileFilesystem::json((object) $render),
            ManifestValidator::OUTPUTS[3] => "/* Generated by SMK: no module CSS in Core profile. */\n",
            ManifestValidator::OUTPUTS[4] => "// Generated by SMK: no module JavaScript in Core profile.\n",
        ];
        Yaml::parse($bytes[ManifestValidator::OUTPUTS[0]], Yaml::PARSE_EXCEPTION_ON_INVALID_TYPE);
        foreach (array_keys($bytes) as $path) {
            $nearestParent = null;
            foreach ($this->fs->inspect($path) as $identity) {
                $this->fs->need($identity === null || $identity['dev'] === $this->fs->identity('')['dev'], 'output: same filesystem required');
                if ($identity !== null && $identity['type'] === 0040000) {
                    $nearestParent = $identity;
                }
            }
            $this->fs->need($nearestParent !== null && ($nearestParent['mode'] & 0300) === 0300, 'output: writable output parent required');
        }
        $ledgerPath = self::STATE.'/current.json';
        $ledgerStat = $this->fs->file($ledgerPath);
        $ledger = $ledgerStat ? json_decode($this->fs->read($ledgerPath), true, flags: JSON_THROW_ON_ERROR) : [];
        $this->fs->need(is_array($ledger), 'ledger: mapping required');
        $operations = [];
        $newLedger = [];
        foreach ($bytes as $path => $content) {
            $before = $this->fs->file($path);
            $known = $ledger[$path] ?? null;
            $this->fs->need(($before === null && $known === null) || ($before !== null && is_array($known) && ($known['owner'] ?? null) === 'generator' && $before['sha256'] === ($known['sha256'] ?? null) && $before['mode'] === ($known['mode'] ?? null) && $before['gid'] === ($known['gid'] ?? null)), 'output '.$path.': unknown, missing or manually modified generated file');
            $operations[$path] = $this->operation($path, $content, $before);
            $newLedger[$path] = ['sha256' => hash('sha256', $content), 'mode' => $before['mode'] ?? 0644, 'gid' => $before['gid'] ?? posix_getegid(), 'owner' => 'generator'];
        }
        $this->fs->need(! array_diff(array_keys($ledger), array_keys($bytes)), 'ledger: removal/uninstall unsupported');
        $operations[$ledgerPath] = $this->operation($ledgerPath, ProfileFilesystem::json($newLedger), $ledgerStat, 0600);
        $needed = [];
        foreach ($operations as $path => $operation) {
            foreach ($operation['chain'] as $absolute => $identity) {
                if ($identity === null && $absolute !== $this->fs->root.'/'.$path) {
                    $needed[substr($absolute, strlen($this->fs->root) + 1)] = 0755;
                }
            }
        }
        unset($needed[self::STATE]);
        ksort($needed);
        $tool = [];
        foreach ([__FILE__, __DIR__.'/ProfileFilesystem.php', __DIR__.'/ManifestValidator.php', dirname(__DIR__, 4).'/tools/smk/init-profile.php'] as $source) {
            $tool[basename($source)] = hash_file('sha256', $source);
        }
        $plan = ['plan_schema' => 1, 'generator' => $tool, 'root' => $this->fs->root, 'root_identity' => $this->fs->inspect(''), 'profile' => $profile, 'manifests' => $manifests, 'edition' => $edition, 'platform' => $platform, 'inputs' => $inputs, 'directories' => $needed, 'operations' => $operations, 'required_bytes' => array_sum(array_map(fn ($op) => strlen($op['after']) + strlen($op['before_bytes'] ?? ''), $operations)) * 3 + 65536, 'recovery' => 'restore before bytes/metadata; quarantine created files; refuse foreign changes'];
        // Include multiple durable journal/atomic-update copies as well as payloads.
        $plan['required_bytes'] += strlen(ProfileFilesystem::json($plan)) * 8 + 1048576;
        $plan['transaction_id'] = substr(self::digest($plan), 0, 24);

        return $plan;
    }

    private function operation(string $path, string $after, ?array $before, int $mode = 0644): array
    {
        $old = $before ? $this->fs->read($path) : null;
        $action = $old === $after ? 'no-op' : ($old === null ? 'create' : 'replace');
        $diff = '--- '.($old === null ? '/dev/null' : $path)."\n+++ ".$path."\n";
        if ($action !== 'no-op') {
            $a = $old === null ? [] : explode("\n", rtrim($old, "\n"));
            $b = explode("\n", rtrim($after, "\n"));
            $diff .= '@@ -'.($a === [] ? '0,0' : '1,'.count($a)).' +1,'.count($b)." @@\n";
            foreach ($a as $line) {
                $diff .= '-'.$line."\n";
            }
            foreach ($b as $line) {
                $diff .= '+'.$line."\n";
            }
        }

        return ['owner' => 'generator', 'action' => $action, 'chain' => $this->fs->inspect($path), 'before' => $before, 'before_bytes' => $old, 'after' => $after, 'after_sha256' => hash('sha256', $after), 'mode' => $before['mode'] ?? $mode, 'gid' => $before['gid'] ?? posix_getegid(), 'diff' => $diff];
    }

    private function pending(): void
    {
        if ($this->fs->file(self::STATE.'/journal.json')) {
            $j = json_decode($this->fs->read(self::STATE.'/journal.json'), true, flags: JSON_THROW_ON_ERROR);
            $this->fs->need(in_array($j['state'] ?? '', ['committed', 'restored'], true), 'journal: recovery required before new init');
        }
    }

    private function context(bool $exclusive): void
    {
        $this->fs->need($exclusive, 'apply/recovery refused: explicit offline-exclusive attestation required; stop readers/writers and control filesystem access');
        $this->fs->need(function_exists('fsync') && function_exists('posix_geteuid'), 'runtime: fsync and POSIX identity required');
        $this->fs->syncDir($this->fs->root);
    }

    private function lock(): mixed
    {
        $this->fs->mkdir(self::STATE, 0700);
        $this->fs->file(self::STATE.'/lock');
        $f = fopen($this->fs->root.'/'.self::STATE.'/lock', 'c+b');
        $this->fs->need($f !== false && flock($f, LOCK_EX | LOCK_NB), 'lock: another initializer active');
        chmod($this->fs->root.'/'.self::STATE.'/lock', 0600);

        return $f;
    }

    private function journal(array $journal): void
    {
        $path = self::STATE.'/journal.json';
        $tmp = self::STATE.'/journal-'.bin2hex(random_bytes(8)).'.json';
        $this->fs->writeNew($tmp, ProfileFilesystem::json($journal));
        $this->fs->rename($tmp, $path);
        $archive = $this->transactionPath($journal).'/journal.json';
        $archiveTmp = $archive.'-'.bin2hex(random_bytes(4));
        $this->fs->writeNew($archiveTmp, ProfileFilesystem::json($journal));
        $this->fs->rename($archiveTmp, $archive);
    }

    // Fault injection is an in-process test seam, never manifest data or a CLI hook.
    public function apply(array $plan, string $acceptedHash, bool $offlineExclusive, ?\Closure $checkpoint = null): string
    {
        $this->context($offlineExclusive);
        $this->fs->need(hash_equals(self::digest($plan), $acceptedHash), 'approval: exact plan SHA-256 required');
        $this->fs->need(($plan['root'] ?? null) === $this->fs->root, 'plan: different root');
        // Before creating staging, validate both bytes and all recorded identities.
        $actual = $this->plan($plan['profile'], $plan['manifests'], $plan['edition']);
        $this->fs->need($actual === $plan, 'plan stale: inputs, paths or destinations changed');
        if (count(array_filter($plan['operations'], fn ($op) => $op['action'] !== 'no-op')) === 0) {
            return 'no-op';
        }
        $lock = $this->lock();
        try {
            $this->pending();
            $this->checkInputs($plan);
            $this->fs->need(disk_free_space($this->fs->root) >= $plan['required_bytes'], 'staging: insufficient disk space');
            // Approval identifies the deterministic plan; each execution owns fresh evidence.
            $attemptId = bin2hex(random_bytes(12));
            $tx = $this->transactionPath(['attempt_id' => $attemptId, 'plan' => $plan]);
            $this->fs->need(! file_exists($this->fs->root.'/'.$tx), 'attempt directory collision: evidence must not be overwritten');
            $this->fs->mkdir($tx, 0700);
            $items = [];
            foreach ($plan['operations'] as $path => $op) {
                $n = count($items);
                $stage = $tx.'/after-'.$n;
                $this->fs->writeNew($stage, $op['after'], $op['mode'], $op['gid']);
                if ($op['before'] !== null) {
                    $this->fs->writeNew($tx.'/before-'.$n, $op['before_bytes']);
                }
                $items[$path] = ['stage' => $stage, 'stage_identity' => $this->fs->file($stage), 'backup' => $op['before'] === null ? null : $tx.'/before-'.$n];
            }
            $created = [self::STATE => $this->fs->identity(self::STATE)];
            // Stage complete; no target has been changed yet.
            $checkpoint?->__invoke('staged', null);
            $this->checkInputs($plan);
            foreach ($plan['operations'] as $path => $op) {
                $this->checkChain($op['chain'], $created);
            }
            foreach ($items as $path => $item) {
                $op = $plan['operations'][$path];
                $this->fs->need($this->fs->file($item['stage']) === $item['stage_identity'] && $item['stage_identity']['sha256'] === $op['after_sha256'], 'staging: integrity mismatch');
                if ($item['backup'] !== null) {
                    $this->fs->need($this->fs->read($item['backup']) === $op['before_bytes'], 'backup: integrity mismatch');
                }
            }
            $journal = ['journal_schema' => 2, 'attempt_id' => $attemptId, 'state' => 'prepared', 'accepted_hash' => $acceptedHash, 'plan' => $plan, 'items' => $items, 'directories' => $created, 'completed' => []];
            $this->journal($journal);
            $journal['state'] = 'applying';
            $this->journal($journal);
            try {
                foreach ($plan['operations'] as $path => $op) {
                    if ($op['action'] === 'no-op') {
                        continue;
                    }
                    $checkpoint?->__invoke('before', $path);
                    $this->checkInputs($plan);
                    $this->checkChain($op['chain'], $created);
                    foreach ($plan['directories'] as $dir => $mode) {
                        if (! isset($created[$dir])) {
                            $this->fs->mkdir($dir, $mode);
                            $created[$dir] = $this->fs->identity($dir);
                            $journal['directories'] = $created;
                            $this->journal($journal);
                        }
                    }
                    $this->checkChain($op['chain'], $created);
                    $this->fs->need($this->fs->file($items[$path]['stage']) === $items[$path]['stage_identity'], 'staging changed');
                    $this->fs->rename($items[$path]['stage'], $path);
                    $this->fs->need($this->fs->file($path)['sha256'] === $op['after_sha256'], 'activation: hash mismatch');
                    $journal['completed'][] = $path;
                    $this->journal($journal);
                    $checkpoint?->__invoke('after', $path);
                }
                $this->checkInputs($plan);
                foreach ($plan['operations'] as $path => $op) {
                    $expected = $op['action'] === 'no-op' ? $op['before'] : $items[$path]['stage_identity'];
                    $this->fs->need($this->fs->file($path) === $expected && $expected['sha256'] === $op['after_sha256'], 'final validation: identity/hash mismatch');
                }
                json_decode($this->fs->read(ManifestValidator::OUTPUTS[1]), true, flags: JSON_THROW_ON_ERROR);
                json_decode($this->fs->read(ManifestValidator::OUTPUTS[2]), true, flags: JSON_THROW_ON_ERROR);
                Yaml::parse($this->fs->read(ManifestValidator::OUTPUTS[0]), Yaml::PARSE_EXCEPTION_ON_INVALID_TYPE);
                $journal['state'] = 'committed';
                $this->journal($journal);

                return 'committed';
            } catch (\Throwable $e) {
                $journal['state'] = 'recovery_required';
                $this->journal($journal);
                throw new RuntimeException('apply interrupted: recovery required; '.$e->getMessage(), previous: $e);
            }
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }

    private function checkInputs(array $plan): void
    {
        $this->fs->need($this->fs->inspect('') === $plan['root_identity'], 'root identity changed');
        foreach ($plan['inputs'] as $path => $chain) {
            $this->fs->need($this->fs->inspect($path) === $chain, 'input identity/hash changed: '.$path);
        }
    }

    private function checkChain(array $chain, array $created): void
    {
        foreach ($chain as $absolute => $expected) {
            $relative = $absolute === $this->fs->root ? '' : substr($absolute, strlen($this->fs->root) + 1);
            $current = $this->fs->inspect($relative);
            $actual = end($current);
            $this->fs->need($actual === ($created[$relative] ?? $expected), 'path identity/hash changed: '.$relative);
        }
    }

    private function transactionPath(array $journal): string
    {
        // Schema 1 archives used the plan id; retain recovery support without moving them.
        $id = $journal['attempt_id'] ?? $journal['plan']['transaction_id'] ?? null;
        $this->fs->need(is_string($id) && preg_match('/\A[a-f0-9]{24}\z/D', $id) === 1, 'journal: invalid execution identity');
        $this->fs->need(($journal['journal_schema'] ?? 1) !== 2 || isset($journal['attempt_id']), 'journal: attempt identity required');

        return self::STATE.'/tx-'.$id;
    }

    private function matchesBefore(?array $current, ?array $before): bool
    {
        if ($current === null || $before === null) {
            return $current === $before;
        }
        foreach (['sha256', 'size', 'uid', 'gid', 'mode', 'mtime', 'type'] as $key) {
            if ($current[$key] !== $before[$key]) {
                return false;
            }
        }

        return true;
    }

    public function recover(bool $offlineExclusive): string
    {
        $this->context($offlineExclusive);
        $lock = $this->lock();
        try {
            $journal = json_decode($this->fs->read(self::STATE.'/journal.json'), true, flags: JSON_THROW_ON_ERROR);
            $plan = $journal['plan'];
            $this->fs->need(self::digest($plan) === $journal['accepted_hash'] && $plan['root'] === $this->fs->root && $plan['root_identity'] === $this->fs->inspect(''), 'recovery: plan/root integrity mismatch');
            if (in_array($journal['state'], ['committed', 'restored'], true)) {
                return $journal['state'];
            }
            $allowed = array_merge(ManifestValidator::OUTPUTS, [self::STATE.'/current.json']);
            $this->fs->need(array_keys($plan['operations']) === $allowed, 'recovery: unexpected operations');
            $this->fs->need(in_array($journal['journal_schema'] ?? null, [1, 2], true), 'recovery: unsupported journal schema');
            $tx = $this->transactionPath($journal);
            // Validate the entire set and all backups before restoring any member.
            $states = [];
            foreach ($plan['operations'] as $path => $op) {
                $n = array_search($path, $allowed, true);
                $item = $journal['items'][$path];
                $this->fs->need($item['stage'] === $tx.'/after-'.$n && $item['backup'] === ($op['before'] === null ? null : $tx.'/before-'.$n), 'recovery: unexpected artifact path');
                if ($item['backup'] !== null) {
                    $this->fs->need($this->fs->read($item['backup']) === $op['before_bytes'] && hash('sha256', $op['before_bytes']) === $op['before']['sha256'], 'recovery: corrupt backup');
                }
                $chain = $op['chain'];
                array_pop($chain);
                $this->checkChain($chain, $journal['directories']);
                $current = $this->fs->file($path);
                $before = $current === $op['before'];
                $after = $current !== null && $current === $item['stage_identity'];
                $restored = $journal['restored'][$path] ?? null;
                $restoredOnTarget = $restored !== null && $restored === $current && $this->matchesBefore($current, $op['before']);
                $this->fs->need($before || $after || $restoredOnTarget, 'recovery: foreign identity/hash; manual decision required: '.$path);
                // A durable restore identity is an intent until it actually occupies the target.
                // If the target is still the known after inode, restore it even with an intent.
                $states[$path] = $after && ! $before;
            }
            foreach (array_reverse($plan['operations'], true) as $path => $op) {
                if (! $states[$path]) {
                    continue;
                }
                $this->fs->need($this->fs->inspect('') === $plan['root_identity'], 'recovery: root changed');
                $parents = $op['chain'];
                array_pop($parents);
                $this->checkChain($parents, $journal['directories']);
                $n = array_search($path, $allowed, true);
                $current = $this->fs->file($path);
                $this->fs->need($current === $journal['items'][$path]['stage_identity'], 'recovery: destination changed');
                if ($op['before'] === null) {
                    $this->fs->rename($path, $tx.'/quarantine-'.$n);
                } else {
                    $restore = $tx.'/restore-'.$n.'-'.bin2hex(random_bytes(4));
                    $this->fs->writeNew($restore, $this->fs->read($journal['items'][$path]['backup']), $op['before']['mode'], $op['before']['gid']);
                    $this->fs->need(touch($this->fs->root.'/'.$restore, $op['before']['mtime']), 'recovery: cannot restore mtime');
                    $f = fopen($this->fs->root.'/'.$restore, 'r');
                    $this->fs->need(fsync($f), 'recovery: flush failed');
                    fclose($f);
                    $journal['restored'][$path] = $this->fs->file($restore);
                    $this->journal($journal);
                    $this->fs->need($this->fs->inspect('') === $plan['root_identity'], 'recovery: root changed');
                    $this->checkChain($parents, $journal['directories']);
                    $this->fs->need($this->fs->file($path) === $journal['items'][$path]['stage_identity'], 'recovery: destination changed after restore intent');
                    $this->fs->need($this->fs->file($restore) === $journal['restored'][$path] && $this->matchesBefore($journal['restored'][$path], $op['before']), 'recovery: restore staging changed');
                    $this->fs->rename($restore, $path);
                    $this->fs->need($this->fs->file($path) === $journal['restored'][$path], 'recovery: restored identity mismatch');
                }
                $journal['restored'][$path] = $this->fs->file($path);
                $this->journal($journal);
            }
            foreach ($plan['operations'] as $path => $op) {
                $current = $this->fs->file($path);
                $this->fs->need($this->matchesBefore($current, $op['before']), 'recovery: final set verification failed');
            }
            $journal['state'] = 'restored';
            $this->journal($journal);

            return 'restored';
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }
}
